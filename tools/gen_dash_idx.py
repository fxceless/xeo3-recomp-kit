r"""Generate ppc\zz_dash_idx.h from THIS dashboard recompile's ppc_import_mapping.cpp.

The dashboard runtime (dashboard\runtime\zz_dash_hook.h) claims a fixed set of xam/kernel
imports by thunk index. Indices belong to one recompile, so they are generated, never
typed. An import the dash does not have gets -1 and is simply never matched.

    python -I tools\gen_dash_idx.py games\dash
(scripts\recompile-dashboard.ps1 runs it for you.)
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kitgame

HERE = str(kitgame.game_dir())
src = open(os.path.join(HERE, "ppc", "ppc_import_mapping.cpp"), encoding="utf-8").read()
idx = {m.group(1): int(m.group(2))
       for m in re.finditer(r"PPC_IMPORT_FUNC_IMPL\(__import__(\w+),\s*(\d+)\)", src)}

WANT = [
    "XUsbcamGetState", "XUsbcamCreate", "XUsbcamDestroy", "XUsbcamGetConfig",
    "XUsbcamSetConfig", "XUsbcamSetView", "XUsbcamSetCaptureMode", "XUsbcamReadFrame",
    "XexLoadImage",
    "XamLoaderLaunchTitle", "XamLoaderLaunchTitleEx", "XamLoaderLaunchTitleForReason",
    "XamContentLaunchImageInternalEx",
    "XamLoaderSetLaunchData", "XamLoaderGetLaunchData", "XamLoaderGetLaunchDataSize",
    "XamInputGetKeystrokeEx",
]
# Without these two the My Games launch cannot work at all; refuse rather than build a
# dashboard that silently ignores the A button.
REQUIRED = ["XamContentLaunchImageInternalEx", "XamLoaderLaunchTitleEx"]

lines = [
    "// GENERATED by tools\\gen_dash_idx.py from this recompile's ppc_import_mapping.cpp.",
    "// Import thunk indices the dashboard runtime claims (-1 = this dash does not import it).",
    "#pragma once",
]
missing = []
for name in WANT:
    v = idx.get(name, -1)
    if v < 0:
        missing.append(name)
    lines.append(f"#define ZZ_DI_{name.upper():<36} {v}")
open(os.path.join(HERE, "ppc", "zz_dash_idx.h"), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")

found = len(WANT) - len(missing)
print(f"zz_dash_idx.h: {found}/{len(WANT)} imports found" + (f" (absent: {', '.join(missing)})" if missing else ""))
bad = [n for n in REQUIRED if n in missing]
if bad:
    print(f"ERROR: the dash does not import {', '.join(bad)} -- this is not the dash the runtime was written for")
    sys.exit(1)

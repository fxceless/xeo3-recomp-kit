r"""Generate ppc\zz_save_idx.h from THIS build's ppc_import_mapping.cpp.

The local-save layer (ppc\zz_save.cpp)
answers a fixed set of xam/kernel imports by thunk index. Indices differ per title and
per recompile, so they are generated, never typed -- the NFS lesson (gen_profile_table.py).
An import this title does not have gets -1 and its case is simply never reached.

Re-run after every XenonRecomp pass:  python -I tools\gen_save_idx.py games\<name>
(scripts\recompile.ps1 does it for you)
"""
import os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kitgame
HERE = str(kitgame.game_dir())
src = open(os.path.join(HERE, "ppc", "ppc_import_mapping.cpp"), encoding="utf-8").read()
idx = {m.group(1): int(m.group(2))
       for m in re.finditer(r"PPC_IMPORT_FUNC_IMPL\(__import__(\w+),\s*(\d+)\)", src)}

WANT = [
    ("GETSIGNINSTATE", "XamUserGetSigninState"), ("GETXUID", "XamUserGetXUID"),
    ("GETNAME", "XamUserGetName"), ("CHECKPRIV", "XamUserCheckPrivilege"),
    ("SHOWSIGNIN", "XamShowSigninUI"),
    ("DEVICESELECTOR", "XamShowDeviceSelectorUI"), ("DEVICESTATE", "XamContentGetDeviceState"),
    ("DEVICEDATA", "XamContentGetDeviceData"),
    ("CREATEENUM", "XamContentCreateEnumerator"), ("ENUMERATE", "XamEnumerate"),
    ("CONTENTCREATE", "XamContentCreate"), ("CONTENTCREATEEX", "XamContentCreateEx"),
    ("CONTENTCLOSE", "XamContentClose"), ("CONTENTFLUSH", "XamContentFlush"),
    ("CONTENTDELETE", "XamContentDelete"), ("GETCREATOR", "XamContentGetCreator"),
    ("GETLICENSEMASK", "XamContentGetLicenseMask"),
    ("SETTHUMBNAIL", "XamContentSetThumbnail"), ("GETTHUMBNAIL", "XamContentGetThumbnail"),
    ("NTCLOSE", "NtClose"), ("NTCREATEFILE", "NtCreateFile"), ("NTOPENFILE", "NtOpenFile"),
    ("NTREADFILE", "NtReadFile"), ("NTWRITEFILE", "NtWriteFile"),
    ("NTQUERYINFOFILE", "NtQueryInformationFile"), ("NTSETINFOFILE", "NtSetInformationFile"),
    ("NTFLUSHFILE", "NtFlushBuffersFile"), ("NTQUERYDIR", "NtQueryDirectoryFile"),
    ("NTQUERYVOLINFO", "NtQueryVolumeInformationFile"),
    ("NTQUERYFULLATTR", "NtQueryFullAttributesFile"),
    # s2: the profile-setting reads behind "signing into gaming profile" + the frame counter
    ("READPROFILE", "XamUserReadProfileSettings"), ("WRITEPROFILE", "XamUserWriteProfileSettings"),
    ("VDSWAP", "VdSwap"), ("GFXCALLBACK", "VdSetGraphicsInterruptCallback"),
    # s2 run 1: the save writer passes a CreateEvent handle in the OVERLAPPED; our answered
    # Nt{Read,Write}File must signal it, through the real kernel's NtSetEvent (never claimed)
    ("NTSETEVENT", "NtSetEvent"),
]
n_imports = max(idx.values()) + 1
lines = ["// GENERATED by tools\\gen_save_idx.py from ppc_import_mapping.cpp -- do not edit.",
         "#pragma once", f"#define ZZ_SAVE_N_IMPORTS {n_imports}"]
names = []
for tag, name in WANT:
    i = idx.get(name, -1)
    lines.append(f"#define ZZ_SI_{tag:<16} {i:4d}   // {name}")
    if i >= 0:
        names.append((i, name))
lines.append("// index -> name, checked at init against the thunk's own name")
lines.append("#define ZZ_SAVE_NAMES { \\")
lines += [f"    {{ {i}, \"{n}\" }}, \\" for i, n in sorted(names)]
lines.append("}")
out = os.path.join(HERE, "ppc", "zz_save_idx.h")
open(out, "w", encoding="utf-8").write("\n".join(lines) + "\n")
print(f"{len(idx)} imports; wrote {out}")
for tag, name in WANT:
    print(f"  {name:32s} {idx.get(name, 'ABSENT')}")

# Recompile a game's XEX into C++ (games\<Game>\ppc\) and iterate until it is clean.
#
#   scripts\recompile.ps1 -Game crackdown
#
# What it does, in order:
#   1. the BOUNDARY LOOP: run XenonRecomp; every "Switch case ... jump outside function"
#      error means the analyser cut a function short, so tools\fix_boundaries.py reads the
#      enclosing function out of the generated source and tools\apply_boundaries.py widens it
#      in config.toml; repeat until there are no switch errors (Fable II: 2027 -> 0 in 15
#      passes). Stale ppc_recomp.*.cpp files are deleted before every pass -- XenonRecomp
#      never deletes surplus files, and a leftover from an earlier pass links twice.
#   2. MMIO: tools\mmio_scan.py finds every instruction that touches the GPU (0x7FC8) or XMA
#      audio (0x7FEA) register blocks and writes them into config.toml's AUTO section, then
#      recompiles once more. Without this a register read returns RAM garbage.
#   3. RUNTIME: copies runtime\ (the hand-written support code) and ppc_precomp_init.cpp into
#      ppc\, writes zz_title.h, generates zz_save_idx.h from this run's import table.
#   4. REPORT: function count, traps, setjmp/longjmp sites, anything else the recompiler
#      complained about, and whether ppc\ is exactly one clean run.
param(
    [Parameter(Mandatory = $true)][string]$Game,
    [int]$MaxPasses = 40,
    [switch]$SkipMmio
)
. "$PSScriptRoot\common.ps1"
$info = Get-GameInfo $Game
$dir = $info.Dir
$ppc = Join-Path $dir "ppc"
$ctxHeader = Join-Path $Recompiler "XenonUtils\ppc_context.h"
Assert-ToolsFresh
New-Item -ItemType Directory -Force -Path $ppc | Out-Null   # XenonRecomp fast-fails if it is missing

function Invoke-Recomp([int]$pass) {
    Get-ChildItem $ppc -Filter "ppc_recomp.*.cpp" -ErrorAction SilentlyContinue | Remove-Item -Force
    $log = Join-Path $dir "recomp.log"
    Push-Location $dir
    try { cmd /c "`"$XenonRecompExe`" config.toml `"$ctxHeader`" > recomp.log 2>&1" } finally { Pop-Location }
    $rc = $LASTEXITCODE
    $lines = Get-Content $log
    $sw = @($lines | Where-Object { $_ -like "ERROR: Switch case*" })
    Set-Content -Path (Join-Path $dir "errors.txt") -Value $sw
    $files = @(Get-ChildItem $ppc -Filter "ppc_recomp.*.cpp").Count
    Say ("  pass {0,2}: {1,5} switch errors, {2} source files (exit {3})" -f $pass, $sw.Count, $files, $rc)
    if ($files -eq 0) { Get-Content $log -Tail 20 | Out-Host; Fail "XenonRecomp produced no source (see games\$Game\recomp.log)" }
    return $sw.Count
}

function Invoke-BoundaryLoop([int]$startPass) {
    $pass = $startPass; $best = [int]::MaxValue; $stuck = 0
    while ($true) {
        $n = Invoke-Recomp $pass
        if ($n -eq 0) { return $pass }
        if ($n -lt $best) { $best = $n; $stuck = 0 } else { $stuck++ }
        if ($stuck -ge 3) { Fail "the switch-error count stopped falling at $best. Read games\$Game\errors.txt (docs\TROUBLESHOOTING.md, 'switch errors')." }
        if ($pass - $startPass + 1 -ge $MaxPasses) { Fail "still $n switch errors after $MaxPasses passes." }
        Invoke-Tool "fix_boundaries.py" @($dir) | Out-Null
        Invoke-Tool "apply_boundaries.py" @($dir) | Out-Host
        $pass++
    }
}

Say "== 1. boundary loop"
$pass = Invoke-BoundaryLoop 1

if (-not $SkipMmio) {
    Say "== 2. MMIO instructions"
    $py = Get-Python
    $found = @()
    foreach ($block in "0x7FC8", "0x7FEA") {
        $out = & $py -I (Join-Path $ToolsDir "mmio_scan.py") $dir $block
        if ($LASTEXITCODE -ne 0) { Fail "mmio_scan.py failed" }
        Say ("  " + ($out | Select-Object -First 1))
        $found += $out
    }
    $cfgPath = Join-Path $dir "config.toml"
    $cfg = [System.IO.File]::ReadAllText($cfgPath)
    $re = '(?s)(# >>> AUTO mmio[^\n]*\n).*?(# <<< AUTO mmio)'
    if ($cfg -notmatch $re) {
        Write-Host "  config.toml has no AUTO mmio markers -- add the lines above to mmio_instructions yourself." -ForegroundColor Yellow
        $found | Out-Host
    } else {
        $body = (($found | ForEach-Object { $_ -replace "`r", "" }) -join "`n") + "`n"
        $new = [regex]::Replace($cfg, $re, { param($m) $m.Groups[1].Value + $body + $m.Groups[2].Value })
        if ($new -ne $cfg) {
            [System.IO.File]::WriteAllText($cfgPath, $new)
            Say "  config.toml updated -> recompiling with the MMIO list"
            $pass = Invoke-BoundaryLoop ($pass + 1)
        } else { Say "  config.toml already up to date" }
    }
}

Say "== 3. runtime"
Copy-Item (Join-Path $RuntimeDir "*") $ppc -Force
Copy-Item (Join-Path $Recompiler "XenonUtils\ppc_precomp_init.cpp") $ppc -Force
$title = "// GENERATED by scripts\recompile.ps1 -- the game's short name (see runtime\zz_title.h).`n#pragma once`n#define ZZ_TITLE `"$Game`"`n"
[System.IO.File]::WriteAllText((Join-Path $ppc "zz_title.h"), $title)
$gen = @(Invoke-Tool "gen_save_idx.py" @($dir)); Say "  $($gen[0])"

Say "== 4. report"
Invoke-Tool "check_ppc_set.py" @($ppc)
$src = Get-ChildItem $ppc -Filter "ppc_recomp.*.cpp"
$count = { param($pat) ($src | Select-String -Pattern $pat -SimpleMatch | Measure-Object).Count }
Say ("  functions          {0}" -f (& $count "PPC_FUNC_IMPL(__imp__"))
$traps = & $count "__builtin_trap();"
Say ("  __builtin_trap     {0}   (each is an instruction the recompiler cannot translate yet)" -f $traps)
Say ("  PPC_SETJMP         {0}" -f (& $count "PPC_SETJMP("))
Say ("  PPC_LONGJMP        {0}" -f (& $count "PPC_LONGJMP("))
Say ("  zz_mftb sites      {0}" -f (& $count "zz_mftb()"))
$other = @(Get-Content (Join-Path $dir "recomp.log") | Where-Object { $_ -like "ERROR*" -and $_ -notlike "ERROR: Switch case*" })
if ($other.Count) {
    Write-Host "  $($other.Count) other recompiler error line(s), first ones:" -ForegroundColor Yellow
    $other | Select-Object -First 10 | ForEach-Object { Write-Host "    $_" }
}
if ($traps -gt 0) {
    Write-Host "  Traps left: find them with  Select-String -Path games\$Game\ppc\ppc_recomp.*.cpp -Pattern __builtin_trap -Context 3,0" -ForegroundColor Yellow
}
Say ""
Say "Next: the checks in docs\TUTORIAL.md step 5 (jump tables, setjmp), then scripts\build.ps1 -Game $Game"
